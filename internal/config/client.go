package config

// Client - настройки клиента, прочитанные из файла конфигурации. Нулевой
// указатель означает, что параметр в файле не задан.
//
// Секретов файл не содержит: пароли и мастер-пароль клиент запрашивает
// интерактивно, а токен доступа хранит отдельно в каталоге клиента.
type Client struct {
	// Server - адрес сервера в виде host:port.
	Server *string `json:"server"`
	// CAFile - путь к PEM-файлу с доверенным сертификатом сервера.
	CAFile *string `json:"ca_file"`
	// Dir - каталог локального состояния клиента.
	Dir *string `json:"dir"`
	// Insecure отключает TLS; предназначено только для локальной отладки.
	Insecure *bool `json:"insecure"`
}
