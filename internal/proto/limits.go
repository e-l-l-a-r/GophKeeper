package proto

const (
	// MaxPayloadSize - максимальный размер зашифрованного содержимого одной
	// записи в байтах (10 МиБ). Сервер отклоняет записи большего размера.
	MaxPayloadSize = 10 << 20

	// MaxMessageSize - максимальный размер одного gRPC-сообщения в байтах:
	// содержимое записи плюс запас на служебные поля. Лимит нужно задать и на
	// сервере (MaxRecvMsgSize), и на клиенте (MaxCallRecvMsgSize): по умолчанию
	// gRPC принимает сообщения не больше 4 МиБ, и крупная запись не пройдёт.
	MaxMessageSize = MaxPayloadSize + 1<<20
)
